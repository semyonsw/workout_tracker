/**
 * A renderable, newest-first log out of anything at all — database rows, a backup
 * file, or a legacy AsyncStorage blob during the migration. `fallback` is what a
 * MISSING array becomes.
 *
 * No `.slice()` any more: the cap is gone with the blob that needed it (rule 6).
 * Everything else about this function is unchanged, because moving the bytes into
 * columns does not make them trustworthy — see rule 4.
 */
function sanitizeWorkouts(raw: unknown, fallback: CompletedWorkout[]): CompletedWorkout[] {
  if (!Array.isArray(raw)) return fallback;
  return raw
    .map(sanitizeWorkout)
    .filter((w): w is CompletedWorkout => w !== null)
    .sort((a, b) => new Date(b.startedAt).getTime() - new Date(a.startedAt).getTime());
}

/**
 * A pin that still points at something, or null.
 *
 * Dropped rather than repaired when the workout is gone: the anchor's whole
 * meaning is "THIS session is number N", and keeping the number while losing the
 * session it belonged to would renumber the log by an arbitrary offset.
 */
function sanitizeNumbering(
  value: unknown,
  workouts: readonly CompletedWorkout[],
): WorkoutNumberAnchor | null {
  if (typeof value !== 'object' || value === null) return null;
  const raw = value as Partial<WorkoutNumberAnchor>;
  if (typeof raw.workoutId !== 'string') return null;
  if (typeof raw.number !== 'number' || !Number.isFinite(raw.number)) return null;
  const number = Math.round(raw.number);
  if (number < 1) return null;
  if (!workouts.some((w) => w.id === raw.workoutId)) return null;
  return { workoutId: raw.workoutId, number };
}

const COUNT_UNITS = new Set(['reps', 'seconds', 'meters', 'rounds']);
const LOAD_MODES = new Set(['external', 'added_bodyweight', 'assisted', 'none']);

function finiteOr(value: unknown, fallback: number): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : fallback;
}

function isIsoish(value: unknown): value is string {
  return typeof value === 'string' && Number.isFinite(new Date(value).getTime());
}

/**
 * A workout the history screen can render, or null.
 *
 * Repaired rather than rejected wherever the damage is cosmetic — a missing
 * duration is a number, not a reason to lose the record of a session that
 * happened. Rejected only when the thing that identifies it (an id, a title, a
 * date) is not there, because a row that cannot say what or when it was is not a
 * record of anything.
 */
function sanitizeWorkout(value: unknown): CompletedWorkout | null {
  if (typeof value !== 'object' || value === null) return null;
  const raw = value as Partial<CompletedWorkout>;

  if (typeof raw.id !== 'string' || typeof raw.title !== 'string') return null;
  if (!isIsoish(raw.startedAt)) return null;

  const sets = Array.isArray(raw.sets)
    ? raw.sets.map(sanitizeSetRow).filter((row): row is SetHistory => row !== null)
    : [];
  const exercises = Array.isArray(raw.exercises)
    ? raw.exercises
        .map((exercise) => sanitizeCompletedExercise(exercise, sets))
        .filter((e): e is CompletedExercise => e !== null)
    : [];

  return {
    id: raw.id,
    title: raw.title,
    ...(typeof raw.routineId === 'string' ? { routineId: raw.routineId } : {}),
    startedAt: raw.startedAt,
    endedAt: isIsoish(raw.endedAt) ? raw.endedAt : raw.startedAt,
    durationMinutes: Math.max(1, Math.round(finiteOr(raw.durationMinutes, 1))),
    setCount: Math.max(0, Math.round(finiteOr(raw.setCount, sets.length))),
    totalVolumeKg: Math.max(0, Math.round(finiteOr(raw.totalVolumeKg, 0))),
    /*
     * `volumeIsPartial` arrived in 0.12.0, so every workout logged before it has a
     * volume figure and no flag. Deriving it is exact rather than a guess: volume
     * used to skip every exercise with `requiresWeight === false` and read
     * assistance as load, so a pre-0.11 workout containing ANY rep-counted set
     * that is not plain external work has a total that undercounts. That is
     * precisely what the flag means.
     */
    volumeIsPartial:
      typeof raw.volumeIsPartial === 'boolean'
        ? raw.volumeIsPartial
        : sets.some((row) => row.countUnit === 'reps' && row.loadMode !== 'external'),
    exercises,
    sets,
  };
}

/**
 * `rows` are the workout's own set rows, and they are what makes `totalCount`
 * survive an upgrade: the field was added in 0.10.0, so every workout logged
 * before it has a summary and no total. Summing the rows recovers the real number
 * rather than showing a 0 for training that happened.
 */
function sanitizeCompletedExercise(
  value: unknown,
  rows: readonly SetHistory[],
): CompletedExercise | null {
  if (typeof value !== 'object' || value === null) return null;
  const raw = value as Partial<CompletedExercise>;
  if (typeof raw.exerciseId !== 'string' || typeof raw.name !== 'string') return null;
  if (typeof raw.summary !== 'string') return null;

  return {
    exerciseId: raw.exerciseId,
    name: raw.name,
    countUnit: COUNT_UNITS.has(raw.countUnit as string) ? raw.countUnit! : 'reps',
    loadMode: LOAD_MODES.has(raw.loadMode as string) ? raw.loadMode! : 'none',
    setCount: Math.max(0, Math.round(finiteOr(raw.setCount, 0))),
    summary: raw.summary,
    totalCount: Math.max(
      0,
      finiteOr(
        raw.totalCount,
        rows
          // Working sets only, matching what `buildCompletedWorkout` writes: a
          // warm-up is a set that does not count, so it must not appear in a
          // total recovered from the rows either.
          .filter((row) => row.exerciseId === raw.exerciseId && !row.isWarmup)
          .reduce((sum, row) => sum + row.count, 0),
      ),
    ),
    topWeightKg:
      typeof raw.topWeightKg === 'number' && Number.isFinite(raw.topWeightKg)
        ? raw.topWeightKg
        : null,
  };
}

/**
 * One set row, rebuilt FIELD BY FIELD, or null.
 *
 * Stricter than the workout around it: these rows are the input to every future
 * suggestion the app makes, and one row with a `NaN` count would poison a verdict
 * rather than break a screen — which is harder to notice and worse. A row missing
 * anything the overload engine or the shorthand indexes into is dropped whole.
 *
 * NAMED KEYS, NOT A SPREAD, and that is the change 0.12.0 made here. This used to
 * be a predicate feeding `{ ...row, isCompleted: true }`, which validated the
 * fields it knew about and copied everything else straight through — so
 * `estimated1RM`, `rpe`, `side`, `partials` and `notes`, all deleted from
 * `SetHistory` this release, would have ridden along in memory out of an old
 * persisted blob or an old backup file and been written back to disk on the next
 * save, forever. Listing the keys is the same argument `sanitizeSettings` makes
 * about `partialize`: a spread writes things you did not mean to write. A field
 * added to `SetHistory` without being named here is now a type error rather than
 * an unchecked value reaching a verdict.
 */
function sanitizeSetRow(value: unknown): SetHistory | null {
  if (typeof value !== 'object' || value === null) return null;
  const row = value as Partial<SetHistory>;

  if (typeof row.id !== 'string') return null;
  if (typeof row.sessionId !== 'string' || typeof row.exerciseId !== 'string') return null;
  if (!isIsoish(row.performedAt)) return null;
  if (!Number.isFinite(row.setIndex) || !Number.isFinite(row.count)) return null;
  if (row.weightKg != null && !Number.isFinite(row.weightKg)) return null;
  if (!COUNT_UNITS.has(row.countUnit as string)) return null;
  if (!LOAD_MODES.has(row.loadMode as string)) return null;
  if (typeof row.isWarmup !== 'boolean') return null;

  return {
    id: row.id,
    sessionId: row.sessionId,
    exerciseId: row.exerciseId,
    performedAt: row.performedAt,
    setIndex: row.setIndex as number,
    weightKg: row.weightKg ?? null,
    count: row.count as number,
    countUnit: row.countUnit as CountUnit,
    loadMode: row.loadMode as LoadMode,
    isWarmup: row.isWarmup,
    // Only completed sets are ever written (`draftToSetHistory`), so a row in the
    // log is a set that happened whatever the blob claims.
    isCompleted: true,
    ...(typeof row.restTakenSeconds === 'number' && Number.isFinite(row.restTakenSeconds)
      ? { restTakenSeconds: Math.max(0, Math.round(row.restTakenSeconds)) }
      : {}),
  };
}

